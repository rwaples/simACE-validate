"""Power study: how often the harness rejects at stated oracle errors.

    pixi run power --case rm_base --reps 10

Each mutation changes the oracle's law, not simACE, so a rejection is what
the harness would report if simACE had that error. ``null`` checks the
oracle against its own draws: its rejection rate is the family-wise
false-positive rate of this one case scored as its own Bonferroni family
(alpha/K over the case's p-values only), which Bonferroni holds at or below
0.05. A full harness run uses a larger K, so its per-case rate is lower.
Writes results/power.md for rm_base and results/power_<case>.md for any
other case.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

from run_harness import RESULTS, ROOT, assign_status, run_case
from structure.mating import MUTATIONS as MATING_MUTATIONS
from structure.mating import SLIM_MUTATIONS

MUTATIONS = {
    "liability": {
        "null": "simACE replaced by one more oracle draw (false-positive rate)",
        "seg_045": "segregation variance 0.45*A instead of 0.5*A",
        "c_by_father": "household by father instead of mother",
        "rA_plus_01": "rA off by +0.1",
    },
    "mating_law": MATING_MUTATIONS,
    "slim_standard": {name: effect for name, (effect, _) in SLIM_MUTATIONS.items()},
}


def main() -> None:
    """Run every mutation over independent harness replicates."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--case", default="rm_base")
    parser.add_argument("--reps", type=int, default=10)
    args = parser.parse_args()
    case = next(c for c in yaml.safe_load((ROOT / "cases.yaml").read_text())["cases"] if c["id"] == args.case)
    if case["oracle"] not in MUTATIONS:
        with_mutations = sorted(
            c["id"] for c in yaml.safe_load((ROOT / "cases.yaml").read_text())["cases"] if c.get("oracle") in MUTATIONS
        )
        parser.error(
            f"case {args.case} (oracle {case['oracle']}) has no mutations; cases with some: {', '.join(with_mutations)}"
        )

    md = [
        "# Power",
        "",
        f"Generated by `power.py --case {args.case} --reps {args.reps}`; do not edit.",
        f"A run rejects when any row of the case fails at alpha/K (R={case['R']}"
        + (f", M={case['M']})." if "M" in case else ")."),
        "K counts this case's p-values only, so each run is one Bonferroni family of this case alone;",
        "a full harness run's K spans every case and its threshold is stricter.",
        "",
        "| Mutation | Effect | Runs rejecting | Rows rejected per run (mean) | Most-rejected rows |",
        "|---|---|---|---|---|",
    ]
    for name, effect in MUTATIONS[case["oracle"]].items():
        rejecting = 0
        n_failed: list[int] = []
        hits: dict[str, int] = {}
        for rep in range(1, args.reps + 1):
            c = case | {
                "id": f"{case['id']}~{name}~{rep}",
                "seed0": case["seed0"] + 1_000_000 + 1000 * rep,
                "mutation": name,
            }
            rows = run_case(c)
            assign_status(rows)
            failed = [r["stat"] for r in rows if r["status"] == "FAIL"]
            rejecting += bool(failed)
            n_failed.append(len(failed))
            for s in failed:
                hits[s] = hits.get(s, 0) + 1
            print(f"{name} rep {rep}: {len(failed)} rows rejected", flush=True)
        top = ", ".join(f"{s} ({k})" for s, k in sorted(hits.items(), key=lambda kv: -kv[1])[:5])
        md.append(f"| {name} | {effect} | {rejecting}/{args.reps} | {sum(n_failed) / args.reps:.1f} | {top} |")
    RESULTS.mkdir(exist_ok=True)
    out = "power.md" if args.case == "rm_base" else f"power_{args.case}.md"
    Path(RESULTS / out).write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
